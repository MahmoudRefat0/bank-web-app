CREATE TABLE users (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR2(100) NOT NULL,
    email         VARCHAR2(150) NOT NULL UNIQUE,
    password_hash VARCHAR2(100) NOT NULL,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE accounts (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR2(20) NOT NULL UNIQUE,
    user_id        NUMBER NOT NULL REFERENCES users (id),
    account_type   VARCHAR2(20) NOT NULL CHECK (account_type IN ('SAVINGS', 'CURRENT')),
    balance        NUMBER(15, 2) DEFAULT 0 NOT NULL CHECK (balance >= 0),
    status         VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE', 'CLOSED')),
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE transactions (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      NUMBER NOT NULL REFERENCES accounts (id),
    tx_type         VARCHAR2(20) NOT NULL CHECK (tx_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER_IN', 'TRANSFER_OUT')),
    amount          NUMBER(15, 2) NOT NULL CHECK (amount > 0),
    balance_after   NUMBER(15, 2) NOT NULL,
    related_account VARCHAR2(20),
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX idx_accounts_user ON accounts (user_id);
CREATE INDEX idx_transactions_account ON transactions (account_id, created_at);
